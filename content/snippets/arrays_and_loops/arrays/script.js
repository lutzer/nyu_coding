// An array is an ordered list of values, written in square brackets.
const colors = ["red", "green", "blue"];

// Items are numbered starting at 0 — not 1.
print(colors[0]);        // first item
print(colors[1]);        // second item
print(colors[2]);        // third item

// `.length` tells you how many items are in the array.
print(colors.length);

// Arrays can hold any kind of value, even mixed:
const stuff = ["Ada", 29, true];
print(stuff[1]);

