// A function is a named chunk of instructions.
// This one has no inputs — the parentheses after the name are empty.
function sayHello() {
  print("Hello!");
}

// Writing the function alone does nothing.
// You have to CALL it: name followed by parentheses.
sayHello();
sayHello();
sayHello();

