// Variables can hold many different kinds of values.

const name    = "Ada";                     // text (a "string") — in quotes
const age     = 29;                        // a number — no quotes
const isOpen  = true;                      // true or false (a "boolean")
const colors  = ["red", "green", "blue"];  // a list (an "array")

print(name);
print(age);
print(isOpen);
print(colors);

